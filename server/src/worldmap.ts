export function getWorldMapSVG(): string {
  let paths = '';
  for (const country of countries) {
    const d = country.parts.map((part) => poly(part)).join(' ');
    paths += `    <path id="${country.id}" d="${d}" />\n`;
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 500" class="world-map">
  <defs>
    <style>
      .world-map { background: #0d0d14; }
      .world-map path {
        fill: #181822;
        stroke: #252530;
        stroke-width: 0.5;
        transition: fill 0.2s ease;
      }
    </style>
  </defs>
  <rect width="1000" height="500" fill="#0d0d14" />
  <g>
${paths}  </g>
</svg>`;
}
