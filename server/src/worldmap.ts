// Simplified world map SVG for analytics dashboard
// Uses equirectangular projection: x = (lon+180)/360*1000, y = (90-lat)/180*500
// Country paths are simplified polygon approximations — recognizable at dashboard scale

// Helper: convert [lon, lat] pairs to SVG path string
function poly(coords: [number, number][]): string {
  return (
    coords
      .map(([lon, lat], i) => {
        const x = ((lon + 180) / 360) * 1000;
        const y = ((90 - lat) / 180) * 500;
        return `${i === 0 ? 'M' : 'L'}${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join(' ') + ' Z'
  );
}

